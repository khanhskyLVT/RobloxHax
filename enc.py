import os
import base64

def encode_lua_file(input_path: str, output_path: str):
    """
    Tự động đọc tệp Lua gốc, mã hóa sang dạng Base64 + Escaped Loader
    giúp ẩn mã nguồn và tránh bị lỗi ký tự điều khiển (NUL bytes).
    """
    if not os.path.exists(input_path):
        print(f"Lỗi: Không tìm thấy tệp {input_path}, boss man.")
        return

    with open(input_path, "rb") as f:
        raw_code = f.read()

    # Mã hóa nội dung sang Base64
    b64_encoded = base64.b64encode(raw_code).decode("utf-8")

    # Tạo Wrapper Loader chuẩn Luau để tự động decode và loadstring khi chạy
    wrapped_lua = f'''--[=[
    Automated Encoded Script Output
    Generated by MrDon Auto-Encoder
]=]
local b64 = "{b64_encoded}"

local b='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
local function decode(data)
    data = string.gsub(data, '[^'..b..'=]', '')
    return (data:gsub('.', function(x)
        if (x == '=') then return '' end
        local r,f='',(b:find(x)-1)
        for i=6,1,-1 do r=r..(f%2^i - f%2^(i-1) >= 1 and '1' or '0') end
        return r
    end):gsub('%d%d%d%d%d%d%d%d', function(x)
        local c=0
        for i=1,8 do c=c+(x:sub(i,i)=='1' and 2^(8-i) or 0) end
        return string.char(c)
    end))
end

local loadedFunc, err = loadstring(decode(b64))
if loadedFunc then
    loadedFunc()
else
    warn("Lỗi giải mã thực thi:", err)
end
'''

    # Ghi tệp kết quả
    output_dir = os.path.dirname(output_path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(wrapped_lua)

    print(f"Thành công: Đã mã hóa {input_path} -> {output_path}, boss man.")

if __name__ == "__main__":
    encode_lua_file("main.lua", "dist/main.lua")